
import os
import json
import glob
import argparse

def main():
    parser = argparse.ArgumentParser(description="Generate markdown summary from evaluation results")
    parser.add_argument("--target_dir", type=str, required=True, help="Root directory containing evaluation results")
    parser.add_argument("--output_md", type=str, required=True, help="Path to save the results.md")
    
    args = parser.parse_args()
    
    target_dir = args.target_dir
    results_md = args.output_md
    
    markdown = '# Evaluation Summary\n\n| 실험 모델 | 날짜 | Pass@1(%) | Pass@1 (No After)(%) | Evaluated/Total | Error(%) | Exception(%) | Missing(%) | Warning(%) | Sorry(%) | EM(%) | BLEU |\n| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |\n'
    
    # Find all summary files (generated by evaluate_infill_proof.py)
    summaries = glob.glob(os.path.join(target_dir, '*', '*', 'evaluation.summary.json'))
    
    data = []
    
    for summary_path in summaries:
        try:
            # Path structure: .../Model/Date/evaluation.summary.json
            parts = summary_path.split(os.sep)
            date = parts[-2]
            model = parts[-3]
            
            with open(summary_path, 'r', encoding='utf-8') as f:
                res = json.load(f)
                pass_rate = res.get('pass_rate', 0.0)
                pass_rate_no_after = res.get('pass_rate_no_after', 0.0)
                error_rate = res.get('error_rate', 0.0)
                warning_rate = res.get('warning_rate', 0.0)
                sorry_rate = res.get('sorry_rate', 0.0)
                exception_rate = res.get('exception_rate', 0.0)
                missing_rate = res.get('missing_rate', 0.0)
                em_rate = res.get('em_rate', 0.0)
                bleu_score = res.get('bleu_score', 0.0)
                
                total = res.get('total', 0)
                evaluated = res.get('evaluated', 0)
                # Fallback for legacy summary files without 'evaluated'
                if 'evaluated' not in res:
                     v = res.get('verified', 0)
                     e = res.get('error', 0)
                     s = res.get('sorry', 0)
                     ex = res.get('exception', 0)
                     evaluated = v + e + s + ex
                if evaluated < total:
                    continue
                     
            data.append({
                'model': model, 
                'date': date, 
                'pass_rate': pass_rate,
                'pass_rate_no_after': pass_rate_no_after,
                'evaluated': evaluated,
                'total': total,
                'error_rate': error_rate,
                'warning_rate': warning_rate,
                'sorry_rate': sorry_rate,
                'exception_rate': exception_rate,
                'missing_rate': missing_rate,
                'em_rate': em_rate,
                'bleu_score': bleu_score
            })
        except Exception as e:
            print(f'Error reading {summary_path}: {e}')
    
    # Sort data
    data.sort(key=lambda x: (x['model'], x['date']))
    
    for entry in data:
        markdown += f"| {entry['model']} | {entry['date']} | {entry['pass_rate']:.2f}% | {entry['pass_rate_no_after']:.2f}% | {entry['evaluated']}/{entry['total']} | {entry['error_rate']:.2f}% | {entry['exception_rate']:.2f}% | {entry['missing_rate']:.2f}% | {entry['warning_rate']:.2f}% | {entry['sorry_rate']:.2f}% | {entry['em_rate']:.2f}% | {entry['bleu_score']:.2f} |\n"
    
    with open(results_md, 'w', encoding='utf-8') as f:
        f.write(markdown)
    
    print(f'Results summary saved to {results_md}')

if __name__ == "__main__":
    main()
